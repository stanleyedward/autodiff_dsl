# bench.py  (python apps/splat2d/bench.py)
# Per-thread reverse-mode stack size and rev_render GPU speed (FPS) for each config,
# a K sweep and a checkpoint-interval sweep. Writes results/bench.md and results/*.png.
# Stack size = what the compiler allocates (rev_render + the _d_rev_ functions it calls;
# only one checkpoint segment runs at a time). slangpy doesn't report real local memory.
import time
from common import *

BLUE, ORANGE, INK, MUTED = '#2a78d6', '#eb6834', '#333333', '#8a8a85'
results_dir = os.path.join(here, 'results')
os.makedirs(results_dir, exist_ok=True)
target = target_image()
H, W = target.shape[:2]


def measure(specs, k, batches=5, runs=50, warmup=10):
    """specs: {label: (config, ck)}, all at K = k. Times rev_render for every spec in
    interleaved batches, so clock and thermal drift hit each config equally.
    Returns {label: dict(slots, ms (median batch mean), lo, hi, error)}."""
    inputs, params = pixel_coords(H, W), init_params(k, H, W)
    rows, dispatch = {}, {}
    for label, (config, ck) in specs.items():
        try:
            r = Renderer(config, k, ck=ck)
        except Exception as e:
            rows[label] = dict(slots=None, error=next(l for l in str(e).splitlines() if l.strip())[:120])
            continue
        _, dout = loss_and_dout(r.render(inputs, params), target)
        run = r.bind('rev_render', r.rev_values(inputs, params, dout), H * W)   # same for every config
        for _ in range(warmup):
            run()
        r.wait()
        dispatch[label] = (r, run)
    ms = {label: [] for label in dispatch}
    for _ in range(batches):
        for label, (r, run) in dispatch.items():
            t0 = time.perf_counter()
            for _ in range(runs):
                run()
                r.wait()
            ms[label].append((time.perf_counter() - t0) * 1000 / runs)
    for label, (r, _) in dispatch.items():
        rows[label] = dict(slots=r.stack_slots, ms=float(np.median(ms[label])),
                           lo=min(ms[label]), hi=max(ms[label]), error=None)
    return rows


def fps(m):
    return 1000 / m['ms']


def fmt(m):
    if m['error']:
        return f"failed: {m['error']} | | |"
    b = m['slots'] * 4
    return (f"{m['slots']} | {b / 1024:.2f} | {b * W * H / 2**20:.1f} | "
            f"{fps(m):.0f} ({1000 / m['hi']:.0f}-{1000 / m['lo']:.0f})")


def style(ax):
    for s in ('top', 'right'):
        ax.spines[s].set_visible(False)
    for s in ('left', 'bottom'):
        ax.spines[s].set_color(MUTED)
    ax.tick_params(colors=INK, labelsize=9)
    ax.grid(axis='y', color='#e6e6e3', linewidth=0.8)
    ax.set_axisbelow(True)


md = ['# Benchmarks\n',
      f'Generated by `python apps/splat2d/bench.py`. {W}x{H} image, one GPU thread per pixel. '
      'Stack = slots the compiler allocates per thread for the reverse pass (4 bytes each); '
      'total = per thread x W*H. FPS = `rev_render` dispatches per second: the median over 5 batches of 50 runs '
      '(range in parentheses), with the configs in each table timed in alternation.\n']

# ---- every config at K = 256 ----
K = 256
md += [f'## Configs (K = {K}, checkpoint := 16)\n',
       '| config | stack slots | KiB / thread | MiB total | rev_render FPS (range) |', '|---|---|---|---|---|']
configs = measure({c: (c, 16) for c in CONFIGS}, K)
for config in CONFIGS:
    md.append(f'| {config} | {fmt(configs[config])} |')
    print(config, configs[config])

# ---- K sweep ----
KS = [32, 64, 128, 256, 512, 1024]
SWEEP = ['+privatize', 'all']
md += ['\n## K sweep (checkpoint := 16 in "all")\n',
       '| K | config | stack slots | KiB / thread | MiB total | rev_render FPS (range) |', '|---|---|---|---|---|---|']
sweep = {c: {} for c in SWEEP}
for k in KS:
    rows = measure({c: (c, 16) for c in SWEEP}, k)
    for c in SWEEP:
        sweep[c][k] = rows[c]
        md.append(f'| {k} | {c} | {fmt(sweep[c][k])} |')
        print(k, c, sweep[c][k])

# ---- checkpoint interval sweep ----
CKS = [4, 8, 16, 32, 64]
md += [f'\n## Checkpoint interval (K = {K}, config "+privatize +checkpoint")\n',
       '| CK | stack slots | KiB / thread | MiB total | rev_render FPS (range) |', '|---|---|---|---|---|']
cks = measure({ck: ('+privatize +checkpoint', ck) for ck in CKS}, K)
for ck in CKS:
    md.append(f'| {ck} | {fmt(cks[ck])} |')
    print('ck', ck, cks[ck])

with open(os.path.join(results_dir, 'bench.md'), 'w') as f:
    f.write('\n'.join(md) + '\n')

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

# memory per config: one series, so one hue and direct labels
names = [c for c in CONFIGS if configs[c]['slots']]
kib = [configs[c]['slots'] * 4 / 1024 for c in names]
fig, ax = plt.subplots(figsize=(7, 3.4))
bars = ax.barh(names[::-1], kib[::-1], color=BLUE, height=0.6)
for b, v in zip(bars, kib[::-1]):
    ax.text(b.get_width() + 0.08, b.get_y() + b.get_height() / 2, f'{v:.2f} KiB',
            va='center', fontsize=9, color=INK)
style(ax)
ax.grid(axis='y', visible=False)
ax.grid(axis='x', color='#e6e6e3', linewidth=0.8)
ax.set_xlabel('reverse-pass stack per thread (KiB)', color=INK)
ax.set_title(f'Per-thread stack, K = {K}', color=INK, fontsize=11, loc='left')
fig.tight_layout()
fig.savefig(os.path.join(results_dir, 'memory.png'), dpi=130)

# FPS and stack vs K: two panels, one y-scale each
fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
for c, color in zip(SWEEP, (BLUE, ORANGE)):
    ok = [k for k in KS if not sweep[c][k]['error']]
    axes[0].plot(ok, [fps(sweep[c][k]) for k in ok], color=color, lw=2, marker='o', ms=5, label=c)
    axes[1].plot(ok, [sweep[c][k]['slots'] * 4 / 1024 for k in ok], color=color, lw=2,
                 marker='o', ms=5, label=c)
for ax, ylabel in zip(axes, ('rev_render FPS', 'stack per thread (KiB)')):
    style(ax)
    ax.set_xscale('log', base=2)
    ax.set_yscale('log')
    ax.set_xticks(KS, [str(k) for k in KS])
    ax.set_xlabel('K (Gaussians)', color=INK)
    ax.set_ylabel(ylabel, color=INK)
axes[1].legend(frameon=False, fontsize=9)
fig.tight_layout()
fig.savefig(os.path.join(results_dir, 'k_sweep.png'), dpi=130)
